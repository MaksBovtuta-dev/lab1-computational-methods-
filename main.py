a = float(input("Введи перше число: "))
b = float(input("Введи друге число: "))

print("Сума:", a + b)
print("Різниця:", a - b)
print("Множення:", a * b)

if b != 0:
    print("Ділення:", a / b)
else:
    print("Ділення: не можна ділити на 0")
